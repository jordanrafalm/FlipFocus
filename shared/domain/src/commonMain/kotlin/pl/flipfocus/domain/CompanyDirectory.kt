    fun byId(id: String): Company? = byId[id]

    /**
     * Case-insensitive local search: prefix matches first, then other substring matches, both
     * alphabetical. An empty query browses the full directory (alphabetical), so Clan can show a
     * company list immediately, before the user types anything.
     */
    fun search(query: String, limit: Int = Int.MAX_VALUE): List<Company> {
        val term = query.trim().lowercase()
        if (term.isEmpty()) return all.sortedBy { it.name }.take(limit)
        val prefix = mutableListOf<Company>()
        val contains = mutableListOf<Company>()
        for ((company, lower) in lowerNames) {
            when {
                lower.startsWith(term) -> prefix += company
                lower.contains(term) -> contains += company
            }
        }
        return (prefix.sortedBy { it.name } + contains.sortedBy { it.name }).take(limit)
    }
